"""Regenerate ``results.json`` in this directory from the current code. Synthetic data only.

    python case_studies/_fixture/make_fixture.py

The tests use the file as an example of the case-study schema. To exercise the optional parts
of the schema, the main pipeline leaves out ``held_out_recording`` and has its ``purged_random``
confidence interval set to null; the ``ridge_alpha_1000`` variant has all five protocols.
``tests/test_validation.py`` checks that the committed file matches what ``build()`` returns.
"""

import datetime as dt
import json
from pathlib import Path
from typing import Any

from sklearn.linear_model import Ridge

from ndz.validation.case_studies import validate_results
from ndz.validation.gap import to_results_json, validation_gap
from ndz.validation.splits import PROTOCOL_ORDER
from ndz.validation.synthetic import make_multisubject

OUT = Path(__file__).resolve().parent / "results.json"
SCRIPT = "case_studies/_fixture/make_fixture.py"
MAIN_PROTOCOLS = ["random_slices", "purged_random", "blocked_in_time", "held_out_subject"]
N_BOOT = 500


def _rounded(x: Any) -> Any:
    if isinstance(x, float):
        return round(x, 4)
    if isinstance(x, dict):
        return {str(k): _rounded(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_rounded(v) for v in x]
    return x


def _run(alpha, protocols):
    d = make_multisubject(n_subjects=4, n_samples=200, seed=7, target_rho=0.99, shared_weight=0.15)
    return validation_gap(d.X, d.y, d.subject, d.recording, d.t, lambda: Ridge(alpha=alpha),
                          protocols=protocols, metric="pearson_r", n_boot=N_BOOT, seed=0)


def build(generated: str | None = None) -> dict:
    """The fixture as a results.json object. ``generated`` defaults to today's date."""
    notes = [
        "SYNTHETIC. Generated by ndz.validation.synthetic.make_multisubject(n_subjects=4, n_samples=200, seed=7, "
        "target_rho=0.99, shared_weight=0.15) (2 recordings per subject, default drift) and "
        "ndz.validation.gap.validation_gap(..., metric='pearson_r', n_boot=500, seed=0) with the current "
        "scoring (each subject scored once on pooled out-of-fold predictions). Used by tests only; "
        "contains no real data.",
        "To exercise optional fields in the schema, the main pipeline leaves out held_out_recording and has its "
        "purged_random confidence interval set to null; the variant has all five protocols.",
    ]
    obj = to_results_json(
        _run(1.0, MAIN_PROTOCOLS), dataset="synthetic_fixture", title="SYNTHETIC FIXTURE (not real data)",
        source={"name": "ndz.validation.synthetic, generated", "url": "", "license": "MIT"},
        task="regression", n_subjects=4, unit="", pipeline="StandardScaler + Ridge(alpha=1)",
        baseline={"name": "chance (r = 0)", "value": 0.0},
        published_claim={"text": "SYNTHETIC example claim band for tests", "low": 0.6, "high": 0.8,
                         "citation": "none (synthetic fixture)"},
        notes=notes, generated=generated or dt.date.today().isoformat(), script=SCRIPT, variants=[])
    for p in obj["protocols"]:
        if p["name"] == "purged_random":
            p["ci_low"] = p["ci_high"] = p["ci_method"] = None
    variant = to_results_json(
        _run(1000.0, list(PROTOCOL_ORDER)), dataset="x", title="x", source={}, task="regression", n_subjects=4,
        unit="", pipeline="StandardScaler + Ridge(alpha=1000)", baseline={}, generated="x", script="x")
    obj["variants"] = [{"name": "ridge_alpha_1000", "pipeline": "StandardScaler + Ridge(alpha=1000)",
                        "protocols": variant["protocols"]}]
    return _rounded(obj)


def main() -> None:
    obj = build()
    problems = validate_results(obj)
    if problems:
        raise SystemExit("fixture does not match the schema: " + "; ".join(problems))
    with open(OUT, "w") as fh:
        json.dump(obj, fh, indent=2)
        fh.write("\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
